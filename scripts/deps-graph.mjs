// Writes docs/deps.html: the app's import graph, drawn with Mermaid.
// Run with `npm run deps:graph`, then open the file in a browser.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const mermaid = execFileSync(
  "npx",
  [
    "depcruise", "app", "components", "lib",
    "--output-type", "mermaid",
    "--collapse", "node_modules/(@[^/]+/[^/]+|[^/]+)",
  ],
  { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 },
);

const html = `<!doctype html>
<meta charset="utf-8">
<title>Import graph</title>
<style>body { margin: 16px; font: 14px system-ui, sans-serif; background: #fff; }</style>
<p>Generated by <code>npm run deps:graph</code> on ${new Date().toLocaleDateString("en-CA")}.</p>
<pre class="mermaid">${mermaid.replace(/</g, "&lt;")}</pre>
<script type="module">
  import mermaid from "https://cdn.jsdelivr.net/npm/mermaid@11.4.1/dist/mermaid.esm.min.mjs";
  mermaid.initialize({ startOnLoad: true, maxTextSize: 1e7, maxEdges: 5000, flowchart: { useMaxWidth: false } });
</script>
`;

writeFileSync("docs/deps.html", html);
console.log("Wrote docs/deps.html");
