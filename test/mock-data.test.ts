/**
 * Checks the mock patients (scripts/mock-patients.ts) and, with MOCK_SQL=1 (`npm run mock`), writes them to
 * supabase/seed/mock-patients.sql with the same validation and cross-check flags the app would store.
 * Running the SQL replaces only these mock rows (fixed ids); everything else is left alone.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { MOCK_PATIENTS, type MockPatient } from "@/scripts/mock-patients";
import { assessmentGaps, normalizeAssessment } from "@/lib/assessment";
import { crossCheck } from "@/lib/crosscheck";
import { type SupportingDoc, docTypesById } from "@/lib/documents";
import { allFields, emptyData, normalize } from "@/lib/form";
import { buildHandoff } from "@/lib/handoff";
import { buildHousingSummary } from "@/lib/housing";
import { validate } from "@/lib/validate";

const TODAY = new Date("2026-10-12T12:00:00");

function build(p: MockPatient) {
  const data = { ...emptyData(allFields), ...normalize(p.referral, allFields) };
  const docs: SupportingDoc[] = p.docs.map((d, i) => ({
    id: `${p.id.slice(0, -2)}${String(10 + i)}`,
    doc_type: d.type,
    label: docTypesById.get(d.type)!.label,
    document_id: null,
    pages: null,
    status: "done",
    data: d.data,
    error: null,
  }));
  const flags = validate(data);
  const docFlags = crossCheck(data, docs, new Date(p.receivedAt).toISOString());
  const assessment = p.assessment && { status: p.assessment.status, data: normalizeAssessment(p.assessment.data) };
  return { data, docs, flags, docFlags, assessment };
}

const built = new Map(MOCK_PATIENTS.map((p) => [p.referral.patient_name as string, { p, ...build(p) }]));
const get = (name: string) => built.get(name)!;

describe("mock patients", () => {
  it("are complete, approved referrals", () => {
    for (const { p, flags, data } of built.values()) {
      expect(flags.filter((f) => f.kind === "missing" || f.kind === "invalid"), p.referral.patient_name as string).toEqual([]);
      expect(data.approved).toBe("Yes");
    }
  });

  it("have every required supporting document and no document conflicts", () => {
    for (const { p, docFlags } of built.values()) {
      expect(docFlags.filter((f) => f.kind === "conflict" || f.message.startsWith("Missing")), p.referral.patient_name as string).toEqual([]);
    }
  });

  it("give the nurse useful alerts", () => {
    const denise = buildHandoff(get("Denise Harper").data, get("Denise Harper").docs, get("Denise Harper").docFlags, TODAY);
    expect(denise.medications.rows.find((r) => r.name === "Oxycodone")?.notes).toContain("Controlled: count and lock");
    const jim = buildHandoff(get("James Whitaker").data, get("James Whitaker").docs, get("James Whitaker").docFlags, TODAY);
    expect(jim.alerts.map((a) => a.label)).toEqual(expect.arrayContaining(["Wound care: not independent", "Insulin-dependent diabetic"]));
  });

  it("cover a draft and two completed assessments with different outcomes", () => {
    expect(assessmentGaps(get("James Whitaker").assessment!.data).length).toBeGreaterThan(0);
    for (const name of ["Maria Santos", "Kevin Brooks"]) expect(assessmentGaps(get(name).assessment!.data), name).toEqual([]);

    const summary = (name: string) => {
      const b = get(name);
      return buildHousingSummary(b.data, b.assessment!.data, b.docs, b.docFlags, TODAY);
    };
    const maria = summary("Maria Santos");
    expect(maria.homelessness.chronic.status).toBe("yes");
    expect(maria.hmis.ready).toBe(true);
    expect(maria.stay.daysLeft).toBe(7);
    expect(maria.plan.map((r) => r.need)).toEqual(expect.arrayContaining(["ID documents", "Primary care connection", "Benefits enrollment"]));
    const due = Object.fromEntries(maria.plan.map((r) => [r.need, r.due]));
    expect(due["ID documents"]).toBe("2026-10-19"); // before the stay ends
    expect(due["Food assistance"]).toBe("2026-11-01"); // 30 days from the assessment

    const kevin = summary("Kevin Brooks");
    expect(kevin.homelessness.chronic.status).toBe("yes");
    expect(kevin.hmis.ready).toBe(false);
    expect(kevin.hmis.issues[0]).toMatch(/HMIS consent/);
    expect(kevin.plan[0].need).toBe("Coordinated Entry");
  });
});

describe.runIf(process.env.MOCK_SQL === "1")("seed file", () => {
  it("writes supabase/seed/mock-patients.sql", () => {
    const json = (v: unknown) => `$json$${JSON.stringify(v)}$json$::jsonb`;
    const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
    const ids = MOCK_PATIENTS.map((p) => q(p.id)).join(", ");
    const lines = [
      "-- Generated by `npm run mock` from scripts/mock-patients.ts. Fictional patients only.",
      "-- Replaces just these rows; deleting the referrals cascades to their documents and assessments.",
      "begin;",
      `delete from "ILLINTAKE_referrals" where id in (${ids});`,
    ];
    for (const { p, data, docs, flags, docFlags, assessment } of built.values()) {
      const received = new Date(p.receivedAt).toISOString();
      lines.push(
        `insert into "ILLINTAKE_referrals" (id, created_at, updated_at, source, status, patient_name, referring_hospital, data, flags, doc_flags, reviewed_at) values (` +
          [q(p.id), q(received), q(received), q("portal"), q("approved"), q(data.patient_name as string), q(data.referring_hospital as string), json(data), json(flags), json(docFlags), q(received)].join(", ") +
          ");",
      );
      for (const d of docs) {
        lines.push(
          `insert into "ILLINTAKE_supporting_docs" (referral_id, created_at, doc_type, label, status, data) values (${[q(p.id), q(received), q(d.doc_type), q(d.label), q("done"), json(d.data)].join(", ")});`,
        );
      }
      if (assessment) {
        const at = q(`${assessment.data.assessment_date}T17:00:00Z`);
        lines.push(
          `insert into "ILLINTAKE_assessments" (referral_id, created_at, updated_at, status, data, completed_at) values (${[q(p.id), at, at, q(assessment.status), json(assessment.data), assessment.status === "complete" ? at : "null"].join(", ")});`,
        );
      }
    }
    lines.push("commit;", "");
    const dir = fileURLToPath(new URL("../supabase/seed/", import.meta.url));
    mkdirSync(dir, { recursive: true });
    writeFileSync(`${dir}mock-patients.sql`, lines.join("\n"));
  });
});
